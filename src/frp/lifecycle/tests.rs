/// A self-signed pair for `app.example.com` (a custom certificate).
fn custom_pair(h: &FakeHost) -> (String, String) {
    let dir = h.dir.join("custom");
    fs::create_dir_all(&dir).unwrap();
    let (cert, key) = (dir.join("cert.pem"), dir.join("key.pem"));
    let path = |p: &std::path::Path| p.to_string_lossy().into_owned();
    let cmd = Cmd::new("openssl").args([
        "req",
        "-x509",
        "-newkey",
        "ec",
        "-pkeyopt",
        "ec_paramgen_curve:prime256v1",
        "-nodes",
        "-days",
        "365",
        "-subj",
        "/CN=app.example.com",
        "-addext",
        "subjectAltName=DNS:app.example.com",
        "-addext",
        "extendedKeyUsage=serverAuth",
        "-keyout",
        &path(&key),
        "-out",
        &path(&cert),
    ]);
    h.ctx.check(&cmd).unwrap();
    (path(&cert), path(&key))
}

#[test]
fn web_mode_with_a_custom_certificate_then_back_to_tcp() {
    let Some(h) = FakeHost::new() else { return };
    let (cert, key) = custom_pair(&h);
    let mut state = web_state(WebTls::Custom { cert, key });
    state.token.clear();
    apply(&h.runtime(), state, change("安装")).unwrap();
    let paths = &h.ctx.paths;
    let conf = fs::read_to_string(paths.frp_root.join("nginx.conf")).unwrap();
    assert!(conf.starts_with("# Managed by Onebox FRP\nuser www-data www-data;\n"));
    assert!(conf.contains("server_name app.example.com; ssl_certificate"));
    assert!(paths.frp_root.join("web-tls/cert.pem").is_file());
    assert!(paths
        .frp_root
        .join("services/onebox-frp-web.json")
        .is_file());
    assert!(h.running(FRP_WEB) && h.enabled(FRP_WEB));
    assert_eq!(mode_of(&paths.frp_web), 0o755);
    assert_eq!(
        mode_of(&paths.frp_web.join("www/.well-known/acme-challenge")),
        0o755
    );

    let installed = model::load(paths).unwrap().unwrap();
    let mut tcp = installed.clone();
    tcp.mode = tcp_state().mode;
    apply(&h.runtime(), tcp, change("配置")).unwrap();
    assert!(!h.running(FRP_WEB) && !h.enabled(FRP_WEB));
    assert!(!unit_file(paths, FRP_WEB).exists());
    assert!(!paths.frp_root.join("nginx.conf").exists());
    assert!(paths.frp_root.join("web-tls/cert.pem").is_file(), "kept");
    assert!(matches!(
        model::load(paths).unwrap().unwrap().mode,
        Mode::Tcp { .. }
    ));
}
