#[test]
fn uninstall_removes_everything_but_foreign_cron_lines() {
    let Some(h) = FakeHost::new() else { return };
    h.set_crontab("0 1 * * * /usr/bin/true\n");
    install_tcp(&h);
    let rt = h.runtime();
    let lock = rt.lock().unwrap();
    uninstall(&rt, &lock).unwrap();
    let paths = &h.ctx.paths;
    for dir in [
        &paths.frp_root,
        &paths.frp_bin,
        &paths.frp_web,
        &paths.frp_log,
        &paths.frp_run,
    ] {
        assert!(!dir.exists(), "{}", dir.display());
    }
    assert!(!unit_file(paths, FRPS).exists());
    assert!(!h.running(FRPS) && !h.enabled(FRPS));
    assert_eq!(h.crontab(), "0 1 * * * /usr/bin/true\n");
    assert!(!journal::exists(paths));
    assert_eq!(
        uninstall(&rt, &lock).unwrap_err().to_string(),
        model::NOT_INSTALLED
    );
}

#[test]
fn v2_cron_lines_are_rewritten_in_place() {
    let Some(h) = FakeHost::new() else { return };
    h.set_crontab(
        "MAILTO=root\n\
         17 3 * * * env ONEBOX_DIR='/etc/onebox' '/usr/local/bin/onebox' frps renew --cron >>'/var/log/onebox-frp/renew.log' 2>&1 # onebox-frps-renew\n\
         @reboot env ONEBOX_DIR='/etc/onebox' '/usr/local/bin/onebox' frps start >>'/var/log/onebox-frp/boot.log' 2>&1 # onebox-frps-boot\n\
         0 1 * * * /usr/bin/true\n",
    );
    install_tcp(&h);
    let tab = h.crontab();
    let lines: Vec<&str> = tab.lines().collect();
    assert_eq!(lines.len(), 3, "{tab}");
    assert_eq!(lines[0], "MAILTO=root");
    assert!(lines[1].ends_with("# onebox:frp-renew"));
    assert_eq!(lines[2], "0 1 * * * /usr/bin/true");
}

