#[test]
fn renew_restarts_frps_only_when_the_control_certificate_changed() {
    let Some(h) = FakeHost::new() else { return };
    install_tcp(&h);
    let rt = h.runtime();
    let lock = rt.lock().unwrap();
    h.exec.clear_history();
    renew(&rt, &lock, true).unwrap();
    let restarted = |h: &FakeHost| {
        h.history()
            .iter()
            .any(|c| c == "systemctl restart onebox-frps")
    };
    assert!(!restarted(&h));
    fs::remove_file(ControlFiles::new(&h.ctx.paths.frp_root).cert()).unwrap();
    renew(&rt, &lock, true).unwrap();
    assert!(restarted(&h));
    assert!(!journal::exists(&h.ctx.paths));
}

