#[test]
fn crashed_transactions_block_net_apply_until_recovered() {
    let Some(h) = FakeHost::new() else { return };
    let original = install_tcp(&h);
    let rt = h.runtime();
    let paths = &h.ctx.paths;
    {
        let lock = rt.lock().unwrap();
        let mut txn = Txn::begin(&rt, &lock, "测试", &journal::targets(paths)).unwrap();
        txn.phase(Phase::WriteFiles).unwrap();
        let mut changed = original.clone();
        changed.token = "f".repeat(64);
        model::save(paths, &changed).unwrap();
        fs::write(paths.frp_bin.join("frps"), fake_frps("0.72.0")).unwrap();
        rt.services().stop(FRPS).unwrap();
        // The process dies here: no commit, no rollback.
    }
    assert!(journal::exists(paths));
    assert_eq!(net_apply(&h.ctx).unwrap_err().to_string(), journal::PENDING);
    {
        // While an FRP operation holds the lock, the hook proceeds.
        let _held = rt.lock().unwrap();
        net_apply(&h.ctx).unwrap();
    }
    let lock = rt.lock().unwrap();
    assert!(recover_locked(&rt, &lock).unwrap());
    assert_eq!(model::load(paths).unwrap().unwrap(), original);
    assert_eq!(
        fs::read(paths.frp_bin.join("frps")).unwrap(),
        fake_frps("0.71.0")
    );
    assert!(h.running(FRPS));
    assert!(!journal::exists(paths));
    drop(lock);
    net_apply(&h.ctx).unwrap();
    assert!(!recover_locked(&rt, &rt.lock().unwrap()).unwrap());
}

